import { readdir, stat } from "node:fs/promises";
import { mkdtemp, mkdir, rm, writeFile } from "node:fs/promises";
import { tmpdir } from "node:os";
import { describe, expect, test } from "vitest";
import { createChampionTipsReader } from "#src/tips/output/champion-reader.ts";
import { fileIssues } from "#src/tips/output/champion-output.ts";
import {
  CHAMPION_FILE_MAX_BYTES,
  CHAMPION_TIPS_TOTAL_MAX_BYTES,
  ChampionTipsFileSchema,
  ChampionTipsIndexSchema,
  championTipsPath,
} from "#src/tips/output/champion-tips.ts";
import { loadFactIndex } from "#src/tips/output/refs.ts";
import { GlossaryFileSchema } from "#src/tips/schema.ts";

const GENERATED = `${import.meta.dir}/../generated`;

async function championFiles(): Promise<string[]> {
  const names = await readdir(`${GENERATED}/champions`).catch(() => []);
  return names.filter((name) => name.endsWith(".json")).toSorted();
}

/**
 * The generated per-champion files, whichever are committed. Nothing is
 * generated by hand: these checks hold the generator's output to its schema,
 * its references to the game facts, and its size to the budget.
 */
describe("the generated champion tips", () => {
  test("parse, and every reference resolves to a game fact or a glossary keyword", async () => {
    const glossary = GlossaryFileSchema.parse(
      await Bun.file(`${GENERATED}/glossary.json`).json(),
    );
    const index = await loadFactIndex(
      glossary.entries.map((entry) => entry.id),
    );
    for (const name of await championFiles()) {
      const file = ChampionTipsFileSchema.parse(
        await Bun.file(`${GENERATED}/champions/${name}`).json(),
      );
      expect(`${file.champion}.json`).toBe(name);
      expect(fileIssues(file, index), name).toEqual([]);
      const ids = [...file.general, ...file.matchups]
        .flatMap((set) => set.tips)
        .map((tip) => tip.id);
      expect(new Set(ids).size, `${name} tip ids`).toBe(ids.length);
    }
  });

  test("are listed by an index that matches the files", async () => {
    const names = await championFiles();
    const indexFile = Bun.file(`${GENERATED}/index.json`);
    if (names.length === 0) {
      expect(await indexFile.exists()).toBe(false);
      return;
    }
    const index = ChampionTipsIndexSchema.parse(await indexFile.json());
    expect(index.champions.map((entry) => entry.file)).toEqual(
      names.map((name) => `champions/${name}`),
    );
    for (const entry of index.champions) {
      const file = ChampionTipsFileSchema.parse(
        await Bun.file(`${GENERATED}/${entry.file}`).json(),
      );
      const tips = [...file.general, ...file.matchups].flatMap(
        (set) => set.tips,
      );
      expect(entry.tips, entry.key).toBe(tips.length);
      expect(entry.hiddenTips, entry.key).toBe(
        tips.filter((tip) => tip.hidden === true).length,
      );
      const { size } = await stat(`${GENERATED}/${entry.file}`);
      expect(entry.bytes, entry.key).toBe(size);
    }
  });

  test("stay within the size budget", async () => {
    let total = 0;
    for (const name of await championFiles()) {
      const { size } = await stat(`${GENERATED}/champions/${name}`);
      expect(size, name).toBeLessThanOrEqual(CHAMPION_FILE_MAX_BYTES);
      total += size;
    }
    expect(total).toBeLessThanOrEqual(CHAMPION_TIPS_TOTAL_MAX_BYTES);
  });
});

describe("the champion tips reader", () => {
  test("returns a champion's visible tips, hides a hidden tip, and hides a set left under the minimum", async () => {
    const directory = await mkdtemp(`${tmpdir()}/scout-champion-tips-`);
    try {
      await mkdir(`${directory}/champions`, { recursive: true });
      const hash = "a".repeat(64);
      const tip = (id: string, hidden = false) => ({
        id,
        text: "Hold Charm until she steps up.",
        refs: [],
        pWrong: hidden ? 0.9 : 0.1,
        ...(hidden ? { hidden: true } : {}),
      });
      await writeFile(
        `${directory}/${championTipsPath("Ahri")}`,
        JSON.stringify({
          schemaVersion: 1,
          champion: "Ahri",
          patch: "16.23",
          model: "m",
          promptVersion: "tips-4",
          general: [
            {
              lane: "middle",
              inputHash: hash,
              tips: [tip("a"), tip("b"), tip("c"), tip("d", true)],
              combos: [],
            },
          ],
          matchups: [
            {
              lane: "middle",
              opponent: "Syndra",
              inputHash: hash,
              tips: [tip("e"), tip("f"), tip("g", true)],
              comboRefs: [],
            },
          ],
        }),
      );
      const reader = createChampionTipsReader(directory);
      const general = await reader.getChampionLaneTips({
        championKey: "Ahri",
        lane: "middle",
      });
      expect(general?.tips.map((entry) => entry.id)).toEqual(["a", "b", "c"]);
      // Two visible tips are under the minimum of three: the set is hidden.
      expect(
        await reader.getMatchupTips({
          championKey: "Ahri",
          opponentKey: "Syndra",
          lane: "middle",
        }),
      ).toBeNull();
      expect(await reader.champion("Nobody")).toBeNull();
      expect(await reader.index()).toBeNull();
    } finally {
      await rm(directory, { recursive: true, force: true });
    }
  });
});
