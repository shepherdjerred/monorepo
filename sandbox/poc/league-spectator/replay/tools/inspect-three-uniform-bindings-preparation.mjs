import { resolve } from "node:path";
import { strict as assert } from "node:assert";
import { prepareThreeUniformBindings } from "./prepare-three-uniform-bindings.mjs";
import {
  adaptThreeUniformBindings,
  THREE_UPSTREAM_SHA256,
} from "./three-uniform-bindings.mjs";
import {
  assertReplayRendererPolicy,
  REPLAY_UNIFORM_BINDINGS_POLICY,
} from "../latest-renderer-policy.mjs";
import { captureDirectSourceInputs } from "./direct-source-inputs.mjs";
import { sha256 } from "../structural-comparison.mjs";
const cache = resolve(process.argv[2] ?? ".cache/replay-spike"),
  inputs = {};
async function raw(path) {
  path = resolve(path);
  const b = await Bun.file(path).bytes(),
    h = await sha256(b);
  if (inputs[path] && inputs[path] !== h)
    throw Error("Preparation proof input drift");
  inputs[path] = h;
  return b;
}
await captureDirectSourceInputs([import.meta.path], raw);
const bytes = await raw(`${cache}/public/vendor/three.module.upstream.js`),
  text = new TextDecoder().decode(bytes),
  adapted = await adaptThreeUniformBindings(text),
  scratch = `${cache}/research/three-ubo-preparation-control`;
assert.equal(await sha256(bytes), THREE_UPSTREAM_SHA256);
let controls = 0;
const seed = async (name, { rawInput = null, derived = bytes } = {}) => {
  const path = `${scratch}/${name}`;
  await Bun.write(`${path}/public/vendor/three.module.js`, derived);
  if (rawInput !== null)
    await Bun.write(`${path}/public/vendor/three.module.upstream.js`, rawInput);
  return path;
};
// A unique child directory ensures the original-seeding case starts raw-free.
const fresh = await seed(`fresh-${process.pid}-${Date.now()}`),
  first = await prepareThreeUniformBindings(fresh);
controls++;
assert.equal(first.derived.sha256, adapted.adaptedSha256);
assert.equal(
  await sha256(
    await Bun.file(`${fresh}/public/vendor/three.module.upstream.js`).bytes(),
  ),
  THREE_UPSTREAM_SHA256,
);
assert.deepEqual(await prepareThreeUniformBindings(fresh), first);
controls++;
await Bun.write(
  `${fresh}/public/vendor/three.module.js`,
  "stale/corrupt generated bytes",
);
assert.equal(
  (await prepareThreeUniformBindings(fresh)).derived.sha256,
  adapted.adaptedSha256,
);
controls++;
const corrupt = bytes.slice();
corrupt[0] ^= 1;
const corruptRaw = await seed("corrupt-raw", {
  rawInput: corrupt,
  derived: "preserve this output on raw rejection",
});
await assert.rejects(
  () => prepareThreeUniformBindings(corruptRaw),
  /Exact THREE/,
);
assert.equal(
  await Bun.file(`${corruptRaw}/public/vendor/three.module.js`).text(),
  "preserve this output on raw rejection",
);
controls++;
const badSeed = await seed(`invalid-seed-${process.pid}-${Date.now()}`, {
  derived: corrupt,
});
await assert.rejects(
  () => prepareThreeUniformBindings(badSeed),
  /Exact original/,
);
controls++;
await assert.rejects(
  () => adaptThreeUniformBindings(adapted.source),
  /Exact THREE/,
);
controls++;
for (const value of [
  undefined,
  {},
  { REPLAY_UNIFORM_BINDINGS_POLICY: "stale" },
]) {
  assert.throws(() => assertReplayRendererPolicy(value), /stale/);
  controls++;
}
assert.doesNotThrow(() =>
  assertReplayRendererPolicy({ REPLAY_UNIFORM_BINDINGS_POLICY }),
);
controls++;
const actual = await raw(`${cache}/public/vendor/three.module.js`),
  provenance = JSON.parse(
    new TextDecoder().decode(
      await raw(`${cache}/public/vendor/three-uniform-bindings.json`),
    ),
  );
assert.equal(await sha256(actual), adapted.adaptedSha256);
assert.equal(provenance.derived.sha256, adapted.adaptedSha256);
assert.equal(provenance.upstream.sha256, THREE_UPSTREAM_SHA256);
for (const [p, h] of Object.entries(inputs))
  assert.equal(await sha256(await Bun.file(p).bytes()), h, p);
const output = `${cache}/research/three-uniform-bindings-preparation.json`;
await Bun.write(
  output,
  JSON.stringify(
    {
      schema: 1,
      kind: "pinned-three-uniform-binding-producer-controls",
      inputs,
      controls,
      upstreamSha256: THREE_UPSTREAM_SHA256,
      adaptedSha256: adapted.adaptedSha256,
      scope: {
        exactUpstreamRequired: true,
        independentRawPreserved: true,
        deterministicIdempotent: true,
        staleOrCorruptDerivedRebuilt: true,
        corruptRawRejectedBeforeOutputMutation: true,
        staleRuntimePolicyRejected: true,
        gpuExecuted: false,
        browserExecuted: false,
      },
    },
    null,
    2,
  ),
);
console.log(
  JSON.stringify({ output, controls, pins: Object.keys(inputs).length }),
);
