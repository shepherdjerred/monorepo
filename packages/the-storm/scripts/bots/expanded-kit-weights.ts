/**
 * Writes `rwfbots/kit-weights.yml`: every personality's weights over the kits
 * added after the personalities were authored (`EXPANDED_KITS`). Personality
 * files keep the weights they were authored with and are never rewritten for
 * new kits; the plugin adds these beside them as it loads the personalities.
 *
 * Each personality's weights are a pure function of its id and archetype, from
 * a seed stream of their own, so the file regenerates bit for bit.
 *
 *   bun scripts/bots/expanded-kit-weights.ts          # write the file
 *   bun scripts/bots/expanded-kit-weights.ts --check  # fail if it is stale
 */
import { readdir } from "node:fs/promises";
import path from "node:path";
import { z } from "zod";
import { ARCHETYPES, EXPANDED_KITS } from "./schema.ts";
import { Rng } from "./random.ts";
import { sampleExpandedKits } from "./traits.ts";

/** The seed stream the expanded kits' weights are drawn from. */
export const EXPANDED_KITS_SEED = "rwf-expanded-kits-v1";

const BOTS = path.join(
  import.meta.dir,
  "..",
  "..",
  "server",
  "owned",
  "plugins",
  "TheStorm",
  "rwfbots",
);

const PersonalityHead = z.object({
  id: z.string().regex(/^[a-z0-9][a-z0-9-]{1,31}$/u),
  archetype: z.enum(ARCHETYPES),
  kits: z.record(z.string(), z.number()),
});

/** The file's YAML for the personalities in `directory`. */
export async function expandedKitWeights(directory: string): Promise<string> {
  const directoryEntries = await readdir(directory);
  const files = directoryEntries
    .filter((name) => name.endsWith(".yml"))
    .toSorted();
  const lines = [
    "# Generated by scripts/bots/expanded-kit-weights.ts; do not edit.",
    "# Each personality's weights over the kits added after it was authored.",
    "personalities:",
  ];
  for (const name of files) {
    const head = PersonalityHead.parse(
      Bun.YAML.parse(await Bun.file(path.join(directory, name)).text()),
    );
    const weights = sampleExpandedKits(
      new Rng(`${EXPANDED_KITS_SEED}:${head.id}`),
      head.archetype,
    );
    const entries = EXPANDED_KITS.filter(
      (kit) => weights[kit] !== undefined && head.kits[kit] === undefined,
    );
    lines.push(entries.length === 0 ? `  "${head.id}": {}` : `  "${head.id}":`);
    for (const kit of entries) {
      lines.push(`    ${kit}: ${String(weights[kit])}`);
    }
  }
  return `${lines.join("\n")}\n`;
}

if (import.meta.main) {
  const file = path.join(BOTS, "kit-weights.yml");
  const yaml = await expandedKitWeights(path.join(BOTS, "personalities"));
  if (Bun.argv.includes("--check")) {
    if ((await Bun.file(file).text()) !== yaml) {
      console.error(
        `${file} is stale; run bun scripts/bots/expanded-kit-weights.ts`,
      );
      process.exit(1);
    }
  } else {
    await Bun.write(file, yaml);
  }
}
