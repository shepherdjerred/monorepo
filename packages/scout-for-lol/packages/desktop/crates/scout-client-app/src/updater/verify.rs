//! Checking a downloaded installer before anything runs it.
//!
//! The signature is the trust root: a minisign signature (the format
//! `cargo packager` writes) checked against the public key compiled into this
//! build. The size and SHA-256 in the manifest catch a truncated or swapped
//! download early and give an operator a second, independent check, but a
//! correct hash alone never makes a file trusted.

use std::fs::File;
use std::io::Read;
use std::path::Path;

use base64::Engine as _;
use base64::engine::general_purpose::STANDARD;
use minisign_verify::{PublicKey, Signature};
use sha2::{Digest as _, Sha256};

use super::manifest::Artifact;

/// Why a download is not trusted.
#[derive(Debug, thiserror::Error)]
pub enum VerifyError {
    /// The compiled-in public key cannot be read. A build with such a key is
    /// broken, so this surfaces on every verification rather than being
    /// skipped.
    #[error("the compiled-in update key is not a minisign public key")]
    PublicKey,
    /// The artifact's signature is not a minisign signature.
    #[error("the artifact signature is not a minisign signature")]
    SignatureEncoding,
    /// The file is not the size the manifest announced.
    #[error("the download is {actual} bytes, the manifest says {expected}")]
    Size {
        /// Bytes the manifest announced.
        expected: u64,
        /// Bytes on disk.
        actual: u64,
    },
    /// The file's SHA-256 is not the one the manifest announced.
    #[error("the download does not match the manifest hash")]
    Hash,
    /// The signature does not verify against the compiled-in key.
    #[error("the signature was not made by this channel's release key: {0}")]
    Signature(String),
    /// The file could not be read.
    #[error("could not read the download: {0}")]
    Io(#[from] std::io::Error),
}

/// Decode the base64 minisign public key a release profile carries.
///
/// # Errors
///
/// [`VerifyError::PublicKey`] when it is not a minisign public key.
pub fn parse_public_key(encoded: &str) -> Result<PublicKey, VerifyError> {
    let text = STANDARD
        .decode(encoded)
        .ok()
        .and_then(|bytes| String::from_utf8(bytes).ok())
        .ok_or(VerifyError::PublicKey)?;
    PublicKey::decode(&text).map_err(|_| VerifyError::PublicKey)
}

fn parse_signature(encoded: &str) -> Result<Signature, VerifyError> {
    let text = STANDARD
        .decode(encoded)
        .ok()
        .and_then(|bytes| String::from_utf8(bytes).ok())
        .ok_or(VerifyError::SignatureEncoding)?;
    Signature::decode(&text).map_err(|_| VerifyError::SignatureEncoding)
}

/// Verify `path` against the manifest's size, hash and signature.
///
/// Reads the file once, in chunks, so a large installer is never held in
/// memory. This is blocking I/O and hashing; callers run it on a blocking
/// thread.
///
/// # Errors
///
/// The first check that fails: size, then hash, then signature.
pub fn verify_file(
    path: &Path,
    artifact: &Artifact,
    public_key: &PublicKey,
) -> Result<(), VerifyError> {
    let signature = parse_signature(&artifact.signature)?;
    let mut file = File::open(path)?;
    let actual = file.metadata()?.len();
    if actual != artifact.size {
        return Err(VerifyError::Size {
            expected: artifact.size,
            actual,
        });
    }
    let mut verifier = public_key
        .verify_stream(&signature)
        .map_err(|error| VerifyError::Signature(error.to_string()))?;
    let mut hasher = Sha256::new();
    let mut buffer = vec![0_u8; 64 * 1024];
    loop {
        let read = file.read(&mut buffer)?;
        if read == 0 {
            break;
        }
        let chunk = &buffer[..read];
        hasher.update(chunk);
        verifier.update(chunk);
    }
    if hex::encode(hasher.finalize()) != artifact.sha256 {
        return Err(VerifyError::Hash);
    }
    verifier
        .finalize()
        .map_err(|error| VerifyError::Signature(error.to_string()))
}

#[cfg(test)]
pub(crate) mod testing {
    //! A throwaway signing key, generated by `cargo packager signer generate`
    //! for these tests only. It signs nothing real: the production keys live in
    //! 1Password and no private key is ever committed.

    /// Base64 of the throwaway minisign public key.
    pub const TEST_PUBLIC_KEY: &str = include_str!("testdata/test-key.pub");
    /// Base64 of the signature of [`PAYLOAD`] by the throwaway key.
    pub const PAYLOAD_SIGNATURE: &str = include_str!("testdata/payload.sig");
    /// Base64 of a public key from a different key pair.
    pub const OTHER_PUBLIC_KEY: &str = include_str!("testdata/other-key.pub");
    /// The bytes [`PAYLOAD_SIGNATURE`] signs.
    pub const PAYLOAD: &[u8] = include_bytes!("testdata/payload.bin");
}

#[cfg(test)]
mod tests {
    use std::path::PathBuf;

    use sha2::{Digest as _, Sha256};

    use super::testing::{OTHER_PUBLIC_KEY, PAYLOAD, PAYLOAD_SIGNATURE, TEST_PUBLIC_KEY};
    use super::{VerifyError, parse_public_key, verify_file};
    use crate::updater::manifest::{Artifact, ArtifactFormat};

    type TestResult = Result<(), Box<dyn std::error::Error>>;

    fn scratch(name: &str, bytes: &[u8]) -> Result<PathBuf, std::io::Error> {
        let directory = std::env::temp_dir().join(format!("scout-verify-{}", uuid::Uuid::new_v4()));
        std::fs::create_dir_all(&directory)?;
        let path = directory.join(name);
        std::fs::write(&path, bytes)?;
        Ok(path)
    }

    fn artifact_for(bytes: &[u8], signature: &str) -> Artifact {
        Artifact {
            url: "https://download.scout-for-lol.com/releases/0.2.0/x.exe".to_owned(),
            sha256: hex::encode(Sha256::digest(bytes)),
            size: bytes.len() as u64,
            signature: signature.trim().to_owned(),
            format: ArtifactFormat::Nsis,
        }
    }

    #[test]
    fn a_good_signature_verifies() -> TestResult {
        let key = parse_public_key(TEST_PUBLIC_KEY.trim())?;
        let path = scratch("good.exe", PAYLOAD)?;
        verify_file(&path, &artifact_for(PAYLOAD, PAYLOAD_SIGNATURE), &key)?;
        Ok(())
    }

    #[test]
    fn a_tampered_file_is_refused_even_with_a_matching_manifest_hash() -> TestResult {
        let key = parse_public_key(TEST_PUBLIC_KEY.trim())?;
        let mut tampered = PAYLOAD.to_vec();
        tampered[0] ^= 0xff;
        let path = scratch("tampered.exe", &tampered)?;
        // A publisher (or an attacker with the bucket) can make size and hash
        // agree with the new bytes; only the signature can refuse them.
        let artifact = artifact_for(&tampered, PAYLOAD_SIGNATURE);
        assert!(matches!(
            verify_file(&path, &artifact, &key),
            Err(VerifyError::Signature(_))
        ));
        Ok(())
    }

    #[test]
    fn a_tampered_file_fails_the_manifest_hash_first() -> TestResult {
        let key = parse_public_key(TEST_PUBLIC_KEY.trim())?;
        let mut tampered = PAYLOAD.to_vec();
        tampered[0] ^= 0xff;
        let path = scratch("tampered.exe", &tampered)?;
        let artifact = artifact_for(PAYLOAD, PAYLOAD_SIGNATURE);
        assert!(matches!(
            verify_file(&path, &artifact, &key),
            Err(VerifyError::Hash)
        ));
        Ok(())
    }

    #[test]
    fn a_signature_by_another_key_is_refused() -> TestResult {
        let other = parse_public_key(OTHER_PUBLIC_KEY.trim())?;
        let path = scratch("good.exe", PAYLOAD)?;
        assert!(matches!(
            verify_file(&path, &artifact_for(PAYLOAD, PAYLOAD_SIGNATURE), &other),
            Err(VerifyError::Signature(_))
        ));
        Ok(())
    }

    #[test]
    fn a_truncated_download_is_refused_by_size() -> TestResult {
        let key = parse_public_key(TEST_PUBLIC_KEY.trim())?;
        let path = scratch("short.exe", &PAYLOAD[..PAYLOAD.len() - 1])?;
        assert!(matches!(
            verify_file(&path, &artifact_for(PAYLOAD, PAYLOAD_SIGNATURE), &key),
            Err(VerifyError::Size { .. })
        ));
        Ok(())
    }

    #[test]
    fn a_garbage_signature_or_key_is_refused() -> TestResult {
        assert!(matches!(
            parse_public_key("not base64!"),
            Err(VerifyError::PublicKey)
        ));
        let key = parse_public_key(TEST_PUBLIC_KEY.trim())?;
        let path = scratch("good.exe", PAYLOAD)?;
        assert!(matches!(
            verify_file(&path, &artifact_for(PAYLOAD, "AAAAAAAAAAAAAAAAAAAA"), &key),
            Err(VerifyError::SignatureEncoding)
        ));
        Ok(())
    }

    #[test]
    fn both_compiled_in_release_keys_are_minisign_public_keys() -> Result<(), VerifyError> {
        use scout_client_core::profile::{BETA, STABLE};
        parse_public_key(STABLE.update_public_key)?;
        parse_public_key(BETA.update_public_key)?;
        Ok(())
    }
}
