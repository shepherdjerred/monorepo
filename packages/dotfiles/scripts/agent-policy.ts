#!/usr/bin/env bun
/**
 * Generates the coding-agent command denylists from one shared source,
 * agent-policy/denied-commands.json:
 *
 * - the `permissions.deny` rules in claude-managed/managed-settings.json
 * - the Codex forbidden prefix rules in private_dot_codex/rules/safety.rules
 *
 *   bun scripts/agent-policy.ts          # rewrite both outputs
 *   bun scripts/agent-policy.ts --check  # exit 1 if either output is stale
 */
import path from "node:path";
import { isDeepStrictEqual } from "node:util";
import { z } from "zod";

const packageRoot = path.resolve(import.meta.dir, "..");
export const policyPath = path.join(
  packageRoot,
  "agent-policy/denied-commands.json",
);
export const claudeSettingsPath = path.join(
  packageRoot,
  "claude-managed/managed-settings.json",
);
export const codexRulesPath = path.join(
  packageRoot,
  "private_dot_codex/rules/safety.rules",
);

// Plain shell words only: Codex falls back to matching the whole script when a
// word needs quoting or expansion (including a `~`), so anything else would
// silently never match there.
const PlainWord = z
  .string()
  .regex(/^[\w./:=-]+$/u, "must be a plain shell word");

/** One argument position: a literal word, or a union of alternative words. */
const TokenSchema = z.union([
  PlainWord,
  z.array(PlainWord).min(2, "must list at least two alternatives"),
]);
export type Token = z.infer<typeof TokenSchema>;

const DeniedCommandSchema = z.strictObject({
  /** Positional argument prefix, matched word by word. */
  pattern: z.array(TokenSchema).min(1),
  /** A flag that triggers the rule anywhere after the prefix. */
  flag: PlainWord.optional(),
  /** Also deny the same command through the `toolkit` passthrough. */
  toolkit: z.boolean().default(false),
  reason: z.string().trim().min(1),
});
export type DeniedCommand = z.infer<typeof DeniedCommandSchema>;

const PolicySchema = z.strictObject({
  commands: z.array(DeniedCommandSchema).min(1),
});

const ClaudeSettingsSchema = z.looseObject({
  permissions: z.looseObject({}).default({}),
});

export function parsePolicy(value: unknown): DeniedCommand[] {
  return PolicySchema.parse(value).commands;
}

function prefixes(command: DeniedCommand): Token[][] {
  return command.toolkit
    ? [command.pattern, ["toolkit", ...command.pattern]]
    : [command.pattern];
}

function expand(pattern: Token[]): string[][] {
  let commands: string[][] = [[]];
  for (const position of pattern) {
    const options = typeof position === "string" ? [position] : position;
    commands = commands.flatMap((prefix) =>
      options.map((option) => [...prefix, option]),
    );
  }
  return commands;
}

/**
 * Claude Code Bash rules. `Bash(sudo *)` denies `sudo` with or without
 * arguments, and its space keeps a word boundary, so `sudoku` stays allowed and
 * `rm -rf / *` never matches `rm -rf /tmp/x`. A flag rule matches the flag
 * anywhere after the prefix.
 */
export function claudeDenyRules(commands: DeniedCommand[]): string[] {
  return commands.flatMap((command) =>
    prefixes(command).flatMap((pattern) =>
      expand(pattern).map((words) => {
        const text = words.join(" ");
        return command.flag === undefined
          ? `Bash(${text} *)`
          : `Bash(${text}*${command.flag}*)`;
      }),
    ),
  );
}

function starlark(position: Token): string {
  return typeof position === "string"
    ? JSON.stringify(position)
    : `[${position.map((option) => JSON.stringify(option)).join(", ")}]`;
}

/**
 * Codex prefix rules. Codex matches a strict positional prefix, so a flag rule
 * only catches the flag directly after the prefix. Claude catches it anywhere.
 */
export function codexRules(commands: DeniedCommand[]): string {
  const rules = commands.flatMap((command) =>
    prefixes(command).map((pattern) => {
      const positions =
        command.flag === undefined ? pattern : [...pattern, command.flag];
      const rendered = positions.map((position) => starlark(position));
      return [
        "prefix_rule(",
        `    pattern = [${rendered.join(", ")}],`,
        `    decision = "forbidden",`,
        `    justification = ${JSON.stringify(command.reason)},`,
        ")",
      ].join("\n");
    }),
  );
  return [
    "# Generated by packages/dotfiles/scripts/agent-policy.ts from",
    "# packages/dotfiles/agent-policy/denied-commands.json. Do not edit by hand.",
    "",
    rules.join("\n\n"),
    "",
  ].join("\n");
}

export function claudeSettings(
  current: unknown,
  commands: DeniedCommand[],
): Record<string, unknown> {
  const settings = ClaudeSettingsSchema.parse(current);
  return {
    ...settings,
    permissions: { ...settings.permissions, deny: claudeDenyRules(commands) },
  };
}

export type Output = { path: string; current: boolean; content: string };

export async function generate(): Promise<Output[]> {
  const commands = parsePolicy(await Bun.file(policyPath).json());
  const settings: unknown = await Bun.file(claudeSettingsPath).json();
  const nextSettings = claudeSettings(settings, commands);
  const rules = codexRules(commands);
  const codexFile = Bun.file(codexRulesPath);
  const currentRules = (await codexFile.exists()) ? await codexFile.text() : "";
  return [
    {
      path: claudeSettingsPath,
      // Compare parsed JSON so formatter whitespace never reads as drift.
      current: isDeepStrictEqual(settings, nextSettings),
      content: `${JSON.stringify(nextSettings, null, 2)}\n`,
    },
    { path: codexRulesPath, current: currentRules === rules, content: rules },
  ];
}

if (import.meta.main) {
  const outputs = await generate();
  const stale = outputs.filter((output) => !output.current);
  if (Bun.argv.includes("--check")) {
    for (const output of stale) {
      console.error(`stale: ${path.relative(packageRoot, output.path)}`);
    }
    if (stale.length > 0) {
      console.error("run: bun packages/dotfiles/scripts/agent-policy.ts");
      process.exit(1);
    }
  } else {
    for (const output of stale) {
      await Bun.write(output.path, output.content);
      console.log(`wrote ${path.relative(packageRoot, output.path)}`);
    }
  }
}
