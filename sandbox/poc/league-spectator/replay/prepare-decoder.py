"""Generate build-specific byte mappings from a hash-checked, offline executable."""
import argparse
import hashlib
import json
from pathlib import Path
import pefile

EXE_SHA256 = '34de26710352fcf4360b27691cecf77843a0ea338cd455be4fabb63fb467984f'
parser = argparse.ArgumentParser()
parser.add_argument('executable', type=Path)
parser.add_argument('output', type=Path)
args = parser.parse_args()
if hashlib.sha256(args.executable.read_bytes()).hexdigest() != EXE_SHA256:
    raise SystemExit('Executable hash mismatch; refusing incompatible decoder tables')
pe = pefile.PE(str(args.executable))
table = pe.get_data(0x1affb00, 256)
def ror(v, n): return ((v >> n) | (v << (8-n))) & 255
def swap(v): return ((v & 0x55) << 1) | ((v >> 1) & 0x55)
# String readers called by animation state decoder RVA 0xf0cb30.
mapping = {
 '1': [(table[swap((swap(v ^ 0x68) + 0x70) & 255)] - 0x7e) & 255 for v in range(256)],
 '2': [((ror(swap(ror(v,5) ^ 8),5) ^ 0xba) + 0x4f) & 255 for v in range(256)],
 '3': [ror(table[(v - 0x62) & 255],1) ^ 0xaf for v in range(256)],
}
for values in mapping.values():
    if len(set(values)) != 256: raise SystemExit('Derived byte mapping is not bijective')
args.output.write_text('// Generated by prepare-decoder.py; exact executable SHA-256: '+EXE_SHA256+'\nexport const animationTables = '+json.dumps(mapping,separators=(',',':'))+';\n')
