import { $ } from "bun";
import path from "node:path";

const whichTypeshare = await $`which typeshare`.quiet().nothrow();
if (whichTypeshare.exitCode !== 0) {
  console.log(
    "typeshare CLI not found in PATH; using pre-generated protocol files.",
  );
  process.exit(0);
}

const protocolDir = import.meta.dir;
const root = path.resolve(protocolDir, "../..");

await $`mkdir -p ${protocolDir}/generated`;
await $`typeshare ${protocolDir} --lang=typescript --output-file=${protocolDir}/generated/index.ts`;

// Output directly to server
const serverDir = path.join(root, "packages/tasknotes-server/src/protocol");
await $`mkdir -p ${serverDir}`;
await $`typeshare ${protocolDir} --lang=typescript --output-file=${serverDir}/generated.ts`;

// Output directly to Apple client
const appleDir = path.join(
  root,
  "packages/tasknotes-macos/Sources/TaskNotesKit/Generated",
);
await $`mkdir -p ${appleDir}`;
const swiftPath = `${appleDir}/Protocol.swift`;
await $`typeshare ${protocolDir} --lang=swift --output-file=${swiftPath}`;

// Post-process Swift file for Swift 6 ExistentialAny and swift-format compatibility
const swiftContent = await Bun.file(swiftPath).text();
const patchedSwift = swiftContent
  .replace(
    /\/\*[\s\S]*?Generated by typeshare[\s\S]*?\*\//,
    "// Generated by typeshare",
  )
  .replace(/from decoder: Decoder/g, "from decoder: any Decoder")
  .replace(/to encoder: Encoder/g, "to encoder: any Encoder")
  .replace(/case type, args/g, "case type\n\t\tcase args")
  .replace(
    /case taskAdd = "TaskAdd",[\s\S]*?labelDelete = "LabelDelete"/,
    `case taskAdd = "TaskAdd"
\t\tcase taskUpdate = "TaskUpdate"
\t\tcase taskDelete = "TaskDelete"
\t\tcase taskComplete = "TaskComplete"
\t\tcase taskUncomplete = "TaskUncomplete"
\t\tcase taskReorder = "TaskReorder"
\t\tcase projectAdd = "ProjectAdd"
\t\tcase projectUpdate = "ProjectUpdate"
\t\tcase projectDelete = "ProjectDelete"
\t\tcase sectionAdd = "SectionAdd"
\t\tcase sectionUpdate = "SectionUpdate"
\t\tcase sectionDelete = "SectionDelete"
\t\tcase labelAdd = "LabelAdd"
\t\tcase labelUpdate = "LabelUpdate"
\t\tcase labelDelete = "LabelDelete"`,
  );
await Bun.write(swiftPath, patchedSwift);

console.log("Facet protocol code generation completed successfully.");
