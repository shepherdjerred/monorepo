"""Extract the exact static integer-degree trig inputs for camera quads."""
import argparse
import hashlib
import json
import struct
from pathlib import Path


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument('cache', type=Path)
    args = parser.parse_args()
    package = args.cache / 'public/decoder-16.21-macos'
    profile = json.loads((package / 'profile.json').read_bytes())
    image = (package / 'image.bin').read_bytes()
    meta = json.loads((package / 'vfx-camera-quads.json').read_bytes())
    sha = lambda b: hashlib.sha256(b).hexdigest()
    if (profile['clientVersion'] != '16.21.829.8620' or
            profile['protocolDigest'] != '20e09df23c66b85e' or
            sha(image) != profile['decoderImageSha256'] or
            sha((package / 'vfx-camera-quads.json').read_bytes()) != profile['vfxCameraQuadsSha256']):
        raise ValueError('Exact camera build required')
    table = meta['degreeTrigTable']
    data = image[table['rva']:table['rva'] + table['bytes']]
    if sha(data) != table['sha256'] or len(data) != 14400:
        raise ValueError('Original camera trig table changed')
    words = struct.unpack('<3600I', data)
    # Original helpers sample sin(degrees) and sin(90-degrees) at 0.1 degrees.
    # Cache construction supplies only the integer degrees 0,-1,...,-359.
    selected = [words[index % 3600] for angle in range(360)
                for index in [-angle * 10, (90 + angle) * 10]]
    lines = [', '.join(f'0x{v:08x}' for v in selected[i:i + 6]) + ','
             for i in range(0, len(selected), 6)]
    output = Path(__file__).resolve().parent.parent / 'latest-direct-effect-camera-table.mjs'
    output.write_bytes(('// Generated by tools/prepare-direct-camera-table.py; static build data only.\n'
                      f'// Original image SHA-256: {sha(image)}\n'
                      f'// Original trig table SHA-256: {sha(data)}\n'
                      'export const directCameraTrig = new Float32Array(\n  new Uint32Array([\n    '
                      + '\n    '.join(lines) + '\n  ]).buffer,\n);\n').encode('utf-8'))
    print(json.dumps({'output': str(output), 'angles': 360, 'tableSha256': sha(data)}))


if __name__ == '__main__':
    main()
