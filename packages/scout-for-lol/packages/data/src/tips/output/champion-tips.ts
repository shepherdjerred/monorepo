import { z } from "zod";
import {
  COMBO_CATEGORIES,
  COMBO_NAME_MAX_LENGTH,
  COMBO_STEPS_MAX,
  COMBOS_MAX,
  COMBO_REFS_MAX,
  COMBO_TEXT_MAX_LENGTH,
} from "#src/tips/combos/combo-schema.ts";
import { GameFactKindSchema } from "#src/game-facts/schema.ts";
import { LaneSchema } from "#src/model/riot/lane.ts";
import { TIP_TEXT_HARD_MAX_LENGTH } from "#src/tips/schema.ts";

/**
 * The generated tips as the app and the public site fetch them: one JSON file
 * per champion, `generated/champions/<ChampionKey>.json`, holding that
 * champion's general sets (with their combos) and its matchup sets, plus a
 * small `generated/index.json` listing the files. Generated by
 * `scripts/pipeline/full-run.ts`, validated in CI, never edited by hand.
 *
 * Every entity a tip or a combo mentions is a reference in the game-fact key
 * format (`src/game-facts/`): `{kind: "ability", key: "Ahri-E"}`, an item or
 * summoner spell by its numeric id, a keyword by its glossary slug. A
 * reference in text carries the character span it covers (UTF-16 offsets, end
 * exclusive), so a page can make that phrase the tooltip trigger.
 */

export const CHAMPION_TIPS_SCHEMA_VERSION = 1;
export const CHAMPION_TIPS_DIRECTORY = "champions";
export const CHAMPION_TIPS_INDEX_PATH = "index.json";

/** A reference to a game fact, and the phrase of a text it covers. */
export const TextRefSchema = z
  .strictObject({
    kind: GameFactKindSchema,
    key: z.string().min(1),
    start: z.number().int().nonnegative(),
    end: z.number().int().positive(),
  })
  .refine((ref) => ref.end > ref.start, {
    message: "a reference needs a non-empty span",
  });
export type TextRef = z.infer<typeof TextRefSchema>;

export const OutputTipSchema = z.strictObject({
  /** Stable: the set and the tip's position when it was written. */
  id: z.string().min(1),
  text: z.string().trim().min(1).max(TIP_TEXT_HARD_MAX_LENGTH),
  refs: z.array(TextRefSchema),
  /** The Decisions API's probability that the tip is wrong, rounded to two places. */
  pWrong: z.number().min(0).max(1),
  /** Kept in the file but not shown: judged very likely wrong and asserting an interaction. */
  hidden: z.literal(true).optional(),
});
export type OutputTip = z.infer<typeof OutputTipSchema>;

/** A combo step a page draws as an icon. */
export const OutputComboStepSchema = z.union([
  z.literal("attack"),
  z.strictObject({ kind: z.literal("ability"), key: z.string().min(1) }),
  z.strictObject({ kind: z.literal("summoner-spell"), key: z.string().min(1) }),
  z.strictObject({ kind: z.literal("item"), key: z.string().min(1) }),
]);
export type OutputComboStep = z.infer<typeof OutputComboStepSchema>;

export const OutputComboSchema = z.strictObject({
  id: z.string().min(1),
  name: z.string().trim().min(1).max(COMBO_NAME_MAX_LENGTH),
  category: z.enum(COMBO_CATEGORIES),
  sequence: z.array(OutputComboStepSchema).max(COMBO_STEPS_MAX),
  when: z.string().trim().min(1).max(COMBO_TEXT_MAX_LENGTH),
  whenRefs: z.array(TextRefSchema),
  text: z.string().trim().min(1).max(COMBO_TEXT_MAX_LENGTH),
  textRefs: z.array(TextRefSchema),
});
export type OutputCombo = z.infer<typeof OutputComboSchema>;

export const OutputComboRefSchema = z.strictObject({
  comboId: z.string().min(1),
  note: z.string().trim().min(1).max(COMBO_TEXT_MAX_LENGTH),
  refs: z.array(TextRefSchema),
});
export type OutputComboRef = z.infer<typeof OutputComboRefSchema>;

const SetStampShape = {
  lane: LaneSchema,
  /** SHA-256 of the prompt version and the grounding facts the set was written from. */
  inputHash: z.string().regex(/^[0-9a-f]{64}$/),
  tips: z.array(OutputTipSchema),
};

export const OutputGeneralSetSchema = z.strictObject({
  ...SetStampShape,
  combos: z.array(OutputComboSchema).max(COMBOS_MAX),
});
export type OutputGeneralSet = z.infer<typeof OutputGeneralSetSchema>;

export const OutputMatchupSetSchema = z.strictObject({
  ...SetStampShape,
  /** Data Dragon key of the opponent. */
  opponent: z.string().min(1),
  comboRefs: z.array(OutputComboRefSchema).max(COMBO_REFS_MAX),
});
export type OutputMatchupSet = z.infer<typeof OutputMatchupSetSchema>;

export const ChampionTipsFileSchema = z.strictObject({
  schemaVersion: z.literal(CHAMPION_TIPS_SCHEMA_VERSION),
  /** Data Dragon key, also the file name. */
  champion: z.string().min(1),
  patch: z.string().min(1),
  model: z.string().min(1),
  promptVersion: z.string().min(1),
  general: z.array(OutputGeneralSetSchema),
  matchups: z.array(OutputMatchupSetSchema),
});
export type ChampionTipsFile = z.infer<typeof ChampionTipsFileSchema>;

export const ChampionTipsIndexEntrySchema = z.strictObject({
  key: z.string().min(1),
  /** Path below the generated directory. */
  file: z.string().min(1),
  lanes: z.array(LaneSchema),
  generalSets: z.number().int().nonnegative(),
  matchupSets: z.number().int().nonnegative(),
  tips: z.number().int().nonnegative(),
  hiddenTips: z.number().int().nonnegative(),
  combos: z.number().int().nonnegative(),
  bytes: z.number().int().positive(),
});
export type ChampionTipsIndexEntry = z.infer<
  typeof ChampionTipsIndexEntrySchema
>;

export const ChampionTipsIndexSchema = z.strictObject({
  schemaVersion: z.literal(CHAMPION_TIPS_SCHEMA_VERSION),
  patch: z.string().min(1),
  model: z.string().min(1),
  promptVersion: z.string().min(1),
  champions: z.array(ChampionTipsIndexEntrySchema),
});
export type ChampionTipsIndex = z.infer<typeof ChampionTipsIndexSchema>;

export function championTipsPath(championKey: string): string {
  return `${CHAMPION_TIPS_DIRECTORY}/${championKey}.json`;
}

/** The size budget of the generated tips: one file, and all of them. */
export const CHAMPION_FILE_MAX_BYTES = 512 * 1024;
export const CHAMPION_TIPS_TOTAL_MAX_BYTES = 24 * 1024 * 1024;
