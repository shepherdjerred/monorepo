function requiredName(
  value: string | undefined,
  kind: string,
  gameId: GameId,
  id: number,
): string {
  if (value === undefined)
    throw new Error(
      `Unsupported ${gameId} ${kind} ID ${String(id)} in game telemetry`,
    );
  return value;
}

export function characterName(gameId: GameId, id: number): string {
  if (gameId === "brawl") {
    switch (id) {
      case 72:
        return "Pokémon Trainer";
      case 73:
        return "Samus / Zero Suit Samus";
      case 74:
        return "Zelda / Sheik";
    }
  }
  return requiredName(characters[gameId][id], "character", gameId, id);
}

export function courseName(gameId: "mk64" | "mkwii", id: number): string {
  return requiredName(courses[gameId][id], "course", gameId, id);
}

export function stageName(gameId: "melee" | "brawl", id: number): string {
  return requiredName(stages[gameId][id], "stage", gameId, id);
}

export function vehicleName(id: number): string {
  return requiredName(vehicles[id], "vehicle", "mkwii", id);
}
