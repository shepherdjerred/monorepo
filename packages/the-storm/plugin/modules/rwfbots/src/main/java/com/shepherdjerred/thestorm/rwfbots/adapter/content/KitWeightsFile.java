package com.shepherdjerred.thestorm.rwfbots.adapter.content;

import com.shepherdjerred.thestorm.core.config.Problem;
import com.shepherdjerred.thestorm.core.config.StrictYaml;
import com.shepherdjerred.thestorm.core.result.Result;
import com.shepherdjerred.thestorm.rwfbots.domain.personality.Personality;
import com.shepherdjerred.thestorm.rwfbots.domain.personality.PersonalityCatalog;
import com.shepherdjerred.thestorm.rwfbots.domain.world.Kit;
import java.io.IOException;
import java.io.UncheckedIOException;
import java.nio.file.Files;
import java.nio.file.Path;
import java.util.ArrayList;
import java.util.EnumMap;
import java.util.List;
import java.util.Locale;
import java.util.Map;

/**
 * {@code plugins/TheStorm/rwfbots/kit-weights.yml}: each personality's weights over the kits added
 * after the personalities were authored (the rest of Red Warfare's and The Storm's new ones),
 * generated by {@code scripts/bots/expanded-kit-weights.ts}. Personality files keep the weights
 * they were authored with and are never rewritten; this file adds the newer kits beside them. Every
 * personality must have an entry, every entry a personality, and no entry may name a kit its file
 * already weighs.
 *
 * @param personalities by personality id, lower-case kit id to weight
 */
record KitWeightsFile(Map<String, Map<String, Double>> personalities) {

  /** Where it lives inside the plugin data folder. */
  static final String FILE = "rwfbots/kit-weights.yml";

  KitWeightsFile {
    personalities = Map.copyOf(personalities);
  }

  /** Reads the file under {@code dataDirectory}. */
  static KitWeightsFile load(Path dataDirectory) {
    var file = dataDirectory.resolve(FILE);
    String yaml;
    try {
      yaml = Files.readString(file);
    } catch (IOException e) {
      throw new UncheckedIOException("Required file " + file + " could not be read", e);
    }
    return switch (StrictYaml.parse(FILE, yaml, KitWeightsFile.class)) {
      case Result.Ok<KitWeightsFile, List<Problem>>(var parsed) -> parsed;
      case Result.Err<KitWeightsFile, List<Problem>>(var problems) ->
          throw new IllegalStateException("Invalid " + FILE + ":\n" + problems);
    };
  }

  /** {@code catalog} with each personality's added kit weights; any mismatch stops the module. */
  PersonalityCatalog applyTo(PersonalityCatalog catalog) {
    var problems = new ArrayList<String>();
    var merged = new ArrayList<Personality>();
    for (var personality : catalog.all()) {
      var added = personalities.get(personality.id());
      if (added == null) {
        problems.add(personality.id() + " has no entry");
        continue;
      }
      var kits = new EnumMap<Kit, Double>(Kit.class);
      kits.putAll(personality.kits());
      for (var entry : added.entrySet()) {
        var kit = Kit.known(entry.getKey().toLowerCase(Locale.ROOT));
        if (kit.isEmpty() || !entry.getKey().equals(kit.orElseThrow().id())) {
          problems.add(personality.id() + " weighs unknown kit " + entry.getKey());
        } else if (kits.putIfAbsent(kit.orElseThrow(), entry.getValue()) != null) {
          problems.add(personality.id() + " already weighs " + entry.getKey() + " in its file");
        }
      }
      merged.add(withKits(personality, kits));
    }
    for (var id : personalities.keySet()) {
      if (catalog.byId(id).isEmpty()) {
        problems.add(id + " is not a personality");
      }
    }
    if (!problems.isEmpty()) {
      throw new IllegalStateException("Invalid " + FILE + ": " + String.join("; ", problems));
    }
    return new PersonalityCatalog(merged);
  }

  private static Personality withKits(Personality p, Map<Kit, Double> kits) {
    return new Personality(
        p.id(),
        p.name(),
        p.skinValue(),
        p.skinSignature(),
        p.skill(),
        p.archetype(),
        p.leverOffsets(),
        kits,
        p.roles(),
        p.style(),
        p.voice(),
        p.lines(),
        p.quirks(),
        p.rivals(),
        p.bio(),
        p.batch(),
        p.retired());
  }
}
