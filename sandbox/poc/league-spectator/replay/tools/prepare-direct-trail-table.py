"""Extract the full original 0.1-degree trig table for direct trail geometry."""
import argparse
import hashlib
import json
from pathlib import Path
import struct
from macho import MachImage


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument('cache', type=Path)
    parser.add_argument('client', type=Path)
    args = parser.parse_args()
    package = args.cache / 'public/decoder-16.21-macos'
    profile = json.loads((package / 'profile.json').read_bytes())
    image = (package / 'image.bin').read_bytes()
    original = MachImage(args.client.read_bytes())
    sha = lambda b: hashlib.sha256(b).hexdigest()
    at, size = 0x20e0090, 3600 * 4
    data = image[at:at+size]
    if (profile['clientVersion'] != '16.21.829.8620' or
        profile['protocolDigest'] != '20e09df23c66b85e' or
        sha(image) != profile['decoderImageSha256'] or sha(original.binary) != profile['sliceSha256'] or
        data != original.image[at:at+size] or
        sha(data) != 'f7b553f3694a37760d7050cd060e1f39698bab4b356baa986a0b8163fccb343a'):
        raise ValueError('Exact original direct trail trigonometry source required')
    words = struct.unpack('<3600I', data)
    lines = [', '.join(f'0x{v:08x}' for v in words[i:i+6]) + ',' for i in range(0,len(words),6)]
    output = Path(__file__).resolve().parent.parent / 'latest-direct-effect-trail-table.mjs'
    output.write_bytes(('// Generated by tools/prepare-direct-trail-table.py; static exact-build data only.\n'
        f'// Original image SHA-256: {sha(image)}\n// Original table SHA-256: {sha(data)}\n'
        'export const directTrailTrig = new Float32Array(\n  new Uint32Array([\n    ' +
        '\n    '.join(lines) + '\n  ]).buffer,\n);\n').encode('utf-8'))
    print(json.dumps({'output':str(output),'samples':len(words),'tableSha256':sha(data)}))


if __name__ == '__main__': main()
