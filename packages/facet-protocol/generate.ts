import { $ } from "bun";
import { mkdir, mkdtemp, rm } from "node:fs/promises";
import os from "node:os";
import path from "node:path";

import {
  generateCSharp,
  parseFacetProtocol,
  type ProtocolSpec,
  writeFileIfChanged,
} from "./generate-csharp.ts";

const IDENTIFIABLE_ENTITY_STRUCTS = new Set([
  "Task",
  "Project",
  "Section",
  "Label",
  "Reminder",
  "Filter",
]);

async function runCommand(cmd: readonly string[], cwd?: string): Promise<void> {
  const proc = Bun.spawn([...cmd], {
    cwd,
    stdout: "pipe",
    stderr: "pipe",
  });
  const [stdout, stderr, exitCode] = await Promise.all([
    new Response(proc.stdout).text(),
    new Response(proc.stderr).text(),
    proc.exited,
  ]);
  if (exitCode !== 0) {
    throw new Error(
      `Command failed (exit ${String(exitCode)}): ${cmd.join(" ")}\n${stderr || stdout}`,
    );
  }
}

function postProcessSwift(rawSwift: string, spec: ProtocolSpec): string {
  for (const entityName of IDENTIFIABLE_ENTITY_STRUCTS) {
    const structDef = spec.structs.find((s) => s.name === entityName);
    const idField = structDef?.fields.find((f) => f.rustName === "id");
    if (
      structDef === undefined ||
      idField === undefined ||
      idField.optional ||
      idField.rustType !== "String"
    ) {
      throw new Error(
        `Identifiable entity struct '${entityName}' must exist and declare non-optional 'id: String'.`,
      );
    }
  }

  return rawSwift
    .replace(
      /\/\*[\s\S]*?Generated by typeshare[\s\S]*?\*\//u,
      "// Generated by typeshare",
    )
    .replace(
      /^public struct ([A-Za-z_][A-Za-z0-9_]*): Codable \{/gmu,
      (_match, structName: string) => {
        const protocols = IDENTIFIABLE_ENTITY_STRUCTS.has(structName)
          ? "Codable, Sendable, Equatable, Hashable, Identifiable"
          : "Codable, Sendable, Equatable, Hashable";
        return `public struct ${structName}: ${protocols} {`;
      },
    )
    .replace(
      /^public enum ([A-Za-z_][A-Za-z0-9_]*): String, Codable \{/gmu,
      "public enum $1: String, Codable, Sendable, Equatable, Hashable {",
    )
    .replace(
      /^public enum ([A-Za-z_][A-Za-z0-9_]*): Codable \{/gmu,
      "public enum $1: Codable, Sendable, Equatable, Hashable {",
    )
    .replaceAll("from decoder: Decoder", "from decoder: any Decoder")
    .replaceAll("to encoder: Encoder", "to encoder: any Encoder")
    .replace(
      /(enum\s+(?:CodingKeys|ContainerCodingKeys)\s*:[^{]+\{\s*)case\s+([\s\S]*?)(\n\s*\})/gu,
      (_match, prefix: string, casesBody: string, suffix: string) => {
        const items = casesBody
          .split(",")
          .map((item) => item.trim())
          .filter((item) => item.length > 0);
        const rendered = items.map((item) => `case ${item}`).join("\n        ");
        return `${prefix}${rendered}${suffix}`;
      },
    );
}

function verifyParserFailLoudlyInvariants(): void {
  let threwBadType = false;
  try {
    parseFacetProtocol(`
      #[typeshare]
      pub struct Bad {
          pub count: u64,
      }
    `);
  } catch {
    threwBadType = true;
  }
  if (!threwBadType) {
    throw new Error(
      "Parser invariant failure: expected unrecognized Rust field type 'u64' to throw.",
    );
  }

  let threwBadSerde = false;
  try {
    parseFacetProtocol(`
      #[typeshare]
      #[serde(rename_all = "camelCase")]
      pub struct BadSerde {
          pub id: String,
      }
    `);
  } catch {
    threwBadSerde = true;
  }
  if (!threwBadSerde) {
    throw new Error(
      "Parser invariant failure: expected unhandled #[serde(...)] attribute to throw.",
    );
  }
}

function extractDelimitedBlock(
  source: string,
  headerIndex: number,
  openChar: string,
  closeChar: string,
): string {
  const openPos = source.indexOf(openChar, headerIndex);
  if (openPos === -1) {
    throw new Error(
      `Missing '${openChar}' after index ${String(headerIndex)}.`,
    );
  }
  let depth = 1;
  let i = openPos + 1;
  while (i < source.length && depth > 0) {
    if (source[i] === openChar) depth += 1;
    else if (source[i] === closeChar) depth -= 1;
    i += 1;
  }
  return source.slice(openPos, i);
}

async function verifyGeneratedParity(
  spec: ProtocolSpec,
  paths: {
    readonly tsIndexPath: string;
    readonly tsServerPath: string;
    readonly swiftPath: string;
    readonly csharpPath: string;
  },
): Promise<void> {
  for (const [label, filePath] of Object.entries(paths)) {
    const file = Bun.file(filePath);
    if (!(await file.exists())) {
      throw new Error(
        `Missing generated protocol file (${label}): ${filePath}`,
      );
    }
  }

  const [tsIndex, tsServer, swiftContent, csharpContent] = await Promise.all([
    Bun.file(paths.tsIndexPath).text(),
    Bun.file(paths.tsServerPath).text(),
    Bun.file(paths.swiftPath).text(),
    Bun.file(paths.csharpPath).text(),
  ]);

  if (tsIndex !== tsServer) {
    throw new Error(
      `Generated TypeScript protocol drift: ${paths.tsIndexPath} !== ${paths.tsServerPath}`,
    );
  }

  for (const unitEnum of spec.unitEnums) {
    if (!tsIndex.includes(`export enum ${unitEnum.name} {`)) {
      throw new Error(`TS missing enum '${unitEnum.name}'.`);
    }
    if (
      !swiftContent.includes(
        `public enum ${unitEnum.name}: String, Codable, Sendable, Equatable, Hashable {`,
      )
    ) {
      throw new Error(
        `Swift missing enum '${unitEnum.name}' with required conformances.`,
      );
    }
    if (!csharpContent.includes(`public enum ${unitEnum.name}`)) {
      throw new Error(`C# missing enum '${unitEnum.name}'.`);
    }
    for (const variant of unitEnum.variants) {
      if (!tsIndex.includes(`${variant} = "${variant}"`)) {
        throw new Error(
          `TS enum '${unitEnum.name}' missing variant '${variant}'.`,
        );
      }
      if (!swiftContent.includes(`= "${variant}"`)) {
        throw new Error(
          `Swift enum '${unitEnum.name}' missing variant '${variant}'.`,
        );
      }
      if (!csharpContent.includes(`    ${variant},`)) {
        throw new Error(
          `C# enum '${unitEnum.name}' missing variant '${variant}'.`,
        );
      }
    }
  }

  for (const structDef of spec.structs) {
    const tsHeader = `export interface ${structDef.name} {`;
    const tsHeaderIdx = tsIndex.indexOf(tsHeader);
    if (tsHeaderIdx === -1) {
      throw new Error(`TS missing interface '${structDef.name}'.`);
    }
    const tsBlock = extractDelimitedBlock(tsIndex, tsHeaderIdx, "{", "}");

    const expectedSwiftConformances = IDENTIFIABLE_ENTITY_STRUCTS.has(
      structDef.name,
    )
      ? "Codable, Sendable, Equatable, Hashable, Identifiable"
      : "Codable, Sendable, Equatable, Hashable";
    const swiftHeader = `public struct ${structDef.name}: ${expectedSwiftConformances} {`;
    const swiftHeaderIdx = swiftContent.indexOf(swiftHeader);
    if (swiftHeaderIdx === -1) {
      throw new Error(
        `Swift missing struct '${structDef.name}' with conformances '${expectedSwiftConformances}'.`,
      );
    }
    const swiftBlock = extractDelimitedBlock(
      swiftContent,
      swiftHeaderIdx,
      "{",
      "}",
    );

    const csharpHeader = `public sealed record ${structDef.name}(`;
    const csharpHeaderIdx = csharpContent.indexOf(csharpHeader);
    if (csharpHeaderIdx === -1) {
      throw new Error(`C# missing sealed record '${structDef.name}'.`);
    }
    const csharpBlock = extractDelimitedBlock(
      csharpContent,
      csharpHeaderIdx,
      "(",
      ")",
    );

    for (const field of structDef.fields) {
      const tsFieldToken = field.optional
        ? `  ${field.rustName}?: `
        : `  ${field.rustName}: `;
      if (!tsBlock.includes(tsFieldToken)) {
        throw new Error(
          `TS interface '${structDef.name}' missing field '${field.rustName}'.`,
        );
      }
      if (!swiftBlock.includes(`public let ${field.rustName}: `)) {
        throw new Error(
          `Swift struct '${structDef.name}' missing field '${field.rustName}'.`,
        );
      }
      if (
        !csharpBlock.includes(
          `[property: JsonPropertyName("${field.rustName}")]`,
        ) ||
        !csharpBlock.includes(`${field.csharpType} ${field.pascalName}`)
      ) {
        throw new Error(
          `C# record '${structDef.name}' missing field '${field.rustName}' (${field.csharpType} ${field.pascalName}).`,
        );
      }
    }
  }

  for (const taggedEnum of spec.taggedEnums) {
    if (!tsIndex.includes(`export type ${taggedEnum.name} =`)) {
      throw new Error(`TS missing discriminated union '${taggedEnum.name}'.`);
    }
    if (
      !swiftContent.includes(
        `public enum ${taggedEnum.name}: Codable, Sendable, Equatable, Hashable {`,
      )
    ) {
      throw new Error(
        `Swift missing enum '${taggedEnum.name}' with required conformances.`,
      );
    }
    if (!csharpContent.includes(`public abstract record ${taggedEnum.name}`)) {
      throw new Error(`C# missing abstract record '${taggedEnum.name}'.`);
    }

    for (const variant of taggedEnum.variants) {
      const tsVariantPattern = new RegExp(
        `\\{\\s*type:\\s*"${variant.name}"[,;]\\s*args:\\s*${variant.payloadType}[,;]?\\s*\\}`,
        "u",
      );
      if (!tsVariantPattern.test(tsIndex)) {
        throw new Error(
          `TS '${taggedEnum.name}' missing variant '${variant.name}(${variant.payloadType})'.`,
        );
      }
      if (
        !swiftContent.includes(`= "${variant.name}"`) ||
        !swiftContent.includes(`(${variant.payloadType})`)
      ) {
        throw new Error(
          `Swift '${taggedEnum.name}' missing variant '${variant.name}(${variant.payloadType})'.`,
        );
      }
      const csharpVariant = `public sealed record ${variant.name}(${variant.payloadType} Args) : ${taggedEnum.name};`;
      if (!csharpContent.includes(csharpVariant)) {
        throw new Error(
          `C# '${taggedEnum.name}' missing variant '${variant.name}(${variant.payloadType})'.`,
        );
      }
    }
  }
}

const protocolDir = import.meta.dir;
const root = path.resolve(protocolDir, "../..");

const generatedDir = path.join(protocolDir, "generated");
const serverDir = path.join(root, "packages/tasknotes-server/src/protocol");
const macosRoot = path.join(root, "packages/tasknotes-macos");
const appleDir = path.join(macosRoot, "Sources/TaskNotesKit/Generated");

const tsIndexPath = path.join(generatedDir, "index.ts");
const tsServerPath = path.join(serverDir, "generated.ts");
const swiftPath = path.join(appleDir, "Protocol.swift");

await mkdir(generatedDir, { recursive: true });

verifyParserFailLoudlyInvariants();
const { outputPath: csharpPath, spec } = await generateCSharp(protocolDir);

const typeshareBin = Bun.which("typeshare");
if (typeshareBin === null) {
  console.log(
    "typeshare CLI not found in PATH; verifying pre-generated protocol files.",
  );
  await verifyGeneratedParity(spec, {
    tsIndexPath,
    tsServerPath,
    swiftPath,
    csharpPath,
  });
  console.log("Facet protocol parity check passed.");
  process.exit(0);
}

await Promise.all([
  mkdir(serverDir, { recursive: true }),
  mkdir(appleDir, { recursive: true }),
]);

const tempDir = await mkdtemp(path.join(os.tmpdir(), "facet-protocol-"));
try {
  const tempTsPath = path.join(tempDir, "index.ts");
  const tempSwiftPath = path.join(tempDir, "Protocol.swift");

  await $`typeshare ${protocolDir} --lang=typescript --output-file=${tempTsPath}`.quiet();
  await $`typeshare ${protocolDir} --lang=swift --output-file=${tempSwiftPath}`.quiet();

  await runCommand(
    ["bunx", "--no-install", "prettier", "--write", tempTsPath],
    root,
  );
  const tsContent = await Bun.file(tempTsPath).text();
  const rawSwift = await Bun.file(tempSwiftPath).text();
  const processedSwift = postProcessSwift(rawSwift, spec);
  await Bun.write(tempSwiftPath, processedSwift);

  const xcrunBin = Bun.which("xcrun");
  if (xcrunBin !== null) {
    const swiftFormatConfig = path.join(macosRoot, ".swift-format");
    await runCommand([
      xcrunBin,
      "swift-format",
      "format",
      "--in-place",
      "--configuration",
      swiftFormatConfig,
      tempSwiftPath,
    ]);
  }

  const finalSwift = await Bun.file(tempSwiftPath).text();

  await Promise.all([
    writeFileIfChanged(tsIndexPath, tsContent),
    writeFileIfChanged(tsServerPath, tsContent),
    writeFileIfChanged(swiftPath, finalSwift),
  ]);
} finally {
  await rm(tempDir, { recursive: true, force: true });
}

await verifyGeneratedParity(spec, {
  tsIndexPath,
  tsServerPath,
  swiftPath,
  csharpPath,
});

console.log("Facet protocol code generation completed successfully.");
